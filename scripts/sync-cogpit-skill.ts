#!/usr/bin/env bun
/**
 * The `cogpit` skill carries two references whose sources live elsewhere: the
 * standalone cogpit-memory skill (published with its npm package) and the
 * remote workspaces guide. This script copies them into
 * .claude/skills/cogpit/references/ and embeds the whole skill in
 * server/agents/bundledSkills.ts, so every build can install it offline.
 *
 * Pass --check in CI to fail when a generated copy has drifted.
 */
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"

const ROOT = join(import.meta.dir, "..")
const SKILL = join(ROOT, ".claude/skills/cogpit")

const SOURCES = [
  { from: "packages/cogpit-memory/skill/SKILL.md", to: "references/memory.md" },
  { from: "docs/remote-workspaces.md", to: "references/remote-workspaces.md" },
] as const

function render(from: string): string {
  const body = readFileSync(join(ROOT, from), "utf8").replace(/^---\n[\s\S]*?\n---\n+/, "")
  return `<!-- Generated from ${from} by scripts/sync-cogpit-skill.ts. Edit the source, then run \`bun run sync-cogpit-skill\`. -->\n\n${body}`
}

const references = SOURCES.map(({ from, to }) => ({ to, path: join(SKILL, to), content: render(from) }))

function skillFiles(directory: string, prefix = ""): [string, string][] {
  return readdirSync(directory, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name)).flatMap((entry): [string, string][] => {
    const name = prefix + entry.name
    if (entry.isDirectory()) return skillFiles(join(directory, entry.name), `${name}/`)
    if (!entry.name.endsWith(".md")) return []
    const generated = references.find((file) => file.to === name)
    return [[name, generated?.content ?? readFileSync(join(directory, entry.name), "utf8")]]
  })
}

const bundled = JSON.stringify(Object.fromEntries(skillFiles(SKILL)), null, 2)
const rendered = [...references, {
  to: "server/agents/bundledSkills.ts",
  path: join(ROOT, "server/agents/bundledSkills.ts"),
  content: `// Generated by scripts/sync-cogpit-skill.ts. Edit the Markdown sources, then regenerate.\nexport const COGPIT_SKILL_FILES: Readonly<Record<string, string>> = ${bundled}\n`,
}]

if (process.argv.slice(2).includes("--check")) {
  const drifted = rendered.filter(({ path, content }) => {
    try {
      return readFileSync(path, "utf8") !== content
    } catch {
      return true
    }
  })
  if (drifted.length > 0) {
    console.error("The cogpit skill is out of sync:")
    for (const { to } of drifted) console.error(`  - ${to}`)
    console.error("Run `bun run sync-cogpit-skill` and commit the generated copies.")
    process.exit(1)
  }
  console.log(`Verified ${rendered.length} generated cogpit skill files`)
  process.exit(0)
}

for (const { to, path, content } of rendered) {
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, content)
  console.log(`  synced ${to}`)
}
